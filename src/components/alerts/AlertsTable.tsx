
"use client";

import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Button } from "@/components/ui/button";
import { Switch } from "@/components/ui/switch";
import type { AlertConfig } from "@/lib/types";
import { Badge } from "@/components/ui/badge";
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuTrigger } from "@/components/ui/dropdown-menu";
import { MoreHorizontal, Edit3, Trash2, BellRing } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { ALERT_TYPES } from "@/lib/constants";
import { format, parseISO } from 'date-fns';

interface AlertsTableProps {
  alerts: AlertConfig[];
  onEdit: (alert: AlertConfig) => void;
  onDelete: (alertId: string) => void;
  onToggleActive: (alertId: string, isActive: boolean) => void;
}

export function AlertsTable({ alerts, onEdit, onDelete, onToggleActive }: AlertsTableProps) {
  const getAlertTypeLabel = (typeValue: string) => {
    return ALERT_TYPES.find(t => t.value === typeValue)?.label || typeValue;
  };

  const formatDateString = (dateString: string) => {
    try {
        const parsedDate = parseISO(dateString);
        return format(parsedDate, 'MM/dd/yyyy');
    } catch (e) {
        // Fallback for potentially invalid date strings if they occur
        return dateString.substring(0,10);
    }
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle className="font-headline flex items-center gap-2">
            <BellRing className="h-6 w-6" />
            Configured Alerts
        </CardTitle>
         <CardDescription>
            Manage your alert configurations. For types like 'Aging Inventory' or 'Customer Satisfaction', tasks are automatically generated by the system if the alert is active.
        </CardDescription>
      </CardHeader>
      <CardContent>
        {alerts.length === 0 ? (
          <p className="text-muted-foreground text-center py-8">No alert configurations yet. Create some using the form above.</p>
        ) : (
        <div className="rounded-md border">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Type</TableHead>
                <TableHead>Details/Item</TableHead>
                <TableHead className="text-right">Threshold</TableHead>
                <TableHead>Created</TableHead>
                <TableHead>Status</TableHead>
                <TableHead className="text-right">Actions</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {alerts.map((alert) => (
                <TableRow key={alert.id} className={!alert.isActive ? "opacity-60" : ""}>
                  <TableCell>
                    <Badge variant={alert.isActive ? "default" : "secondary"}>
                      {getAlertTypeLabel(alert.type)}
                    </Badge>
                  </TableCell>
                  <TableCell className="font-medium">
                    {alert.type === 'low_stock' || alert.type === 'listing_expiration' ? `${alert.itemName || 'N/A'}: ` : ""} {alert.details}
                  </TableCell>
                  <TableCell className="text-right">
                    {alert.type === "low_stock" && alert.threshold !== undefined ? alert.threshold : "N/A"}
                  </TableCell>
                  <TableCell>{formatDateString(alert.creationDate)}</TableCell>
                  <TableCell>
                     <Switch
                        checked={alert.isActive}
                        onCheckedChange={(checked) => onToggleActive(alert.id, checked)}
                        aria-label={alert.isActive ? "Deactivate alert" : "Activate alert"}
                      />
                  </TableCell>
                  <TableCell className="text-right">
                    <DropdownMenu>
                      <DropdownMenuTrigger asChild>
                        <Button variant="ghost" className="h-8 w-8 p-0">
                          <span className="sr-only">Open menu</span>
                          <MoreHorizontal className="h-4 w-4" />
                        </Button>
                      </DropdownMenuTrigger>
                      <DropdownMenuContent align="end">
                        <DropdownMenuItem onClick={() => onEdit(alert)}>
                          <Edit3 className="mr-2 h-4 w-4" /> Edit
                        </DropdownMenuItem>
                        <DropdownMenuItem onClick={() => onDelete(alert.id)} className="text-destructive focus:text-destructive focus:bg-destructive/10">
                          <Trash2 className="mr-2 h-4 w-4" /> Delete
                        </DropdownMenuItem>
                      </DropdownMenuContent>
                    </DropdownMenu>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
        )}
      </CardContent>
    </Card>
  );
}
