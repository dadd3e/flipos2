
"use client";

import { Bar, BarChart, CartesianGrid, XAxis, YAxis, Tooltip, Legend, ResponsiveContainer } from 'recharts';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { ChartContainer, ChartTooltip, ChartTooltipContent, ChartLegend, ChartLegendContent, type ChartConfig } from "@/components/ui/chart";
import type { MonthlySpending, SpendingCategory } from "@/lib/types";
import { SPENDING_CATEGORIES_CONFIG } from "@/lib/reportingUtils";

interface SpendingChartViewProps {
  data: MonthlySpending[]; // Expects data to be sorted with oldest month first for chart
}

const chartConfig = SPENDING_CATEGORIES_CONFIG.reduce((acc, category) => {
  acc[category.id] = {
    label: category.label,
    color: category.chartColor, // Use the HSL color string from config
  };
  return acc;
}, {} as ChartConfig);

export function SpendingChartView({ data }: SpendingChartViewProps) {
  if (data.length === 0) {
    return (
      <Card>
        <CardHeader>
          <CardTitle>Monthly Spending Chart</CardTitle>
          <CardDescription>No data available to display the chart. Please check your filters or log spending data.</CardDescription>
        </CardHeader>
        <CardContent className="flex items-center justify-center h-[300px]">
          <p className="text-muted-foreground">No chart data.</p>
        </CardContent>
      </Card>
    );
  }
  
  return (
    <Card>
      <CardHeader>
        <CardTitle className="font-headline">Monthly Spending Breakdown</CardTitle>
        <CardDescription>Stacked bar chart showing spending categories per month.</CardDescription>
      </CardHeader>
      <CardContent>
        <ChartContainer config={chartConfig} className="min-h-[300px] w-full">
          <ResponsiveContainer width="100%" height={350}>
            <BarChart data={data} accessibilityLayer>
              <CartesianGrid vertical={false} />
              <XAxis
                dataKey="monthLabel"
                tickLine={false}
                tickMargin={10}
                axisLine={false}
                // tickFormatter={(value) => value.slice(0, 3)} // Abbreviate month if needed
              />
              <YAxis tickLine={false} axisLine={false} />
              <ChartTooltip
                cursor={false}
                content={<ChartTooltipContent indicator="dot" hideLabel />}
              />
              <ChartLegend content={<ChartLegendContent />} />
              
              {SPENDING_CATEGORIES_CONFIG.map(category => (
                <Bar
                  key={category.id}
                  dataKey={category.id}
                  fill={`var(--color-${category.id})`} // Use the CSS variable generated by ChartStyle
                  stackId="a"
                  radius={[4, 4, 0, 0]}
                  name={category.label}
                />
              ))}
            </BarChart>
          </ResponsiveContainer>
        </ChartContainer>
      </CardContent>
    </Card>
  );
}

